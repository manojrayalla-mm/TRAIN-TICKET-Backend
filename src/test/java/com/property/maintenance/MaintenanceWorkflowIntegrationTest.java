package com.property.maintenance;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.property.maintenance.dto.AssignTechnicianDto;
import com.property.maintenance.dto.MaintenanceRequestDto;
import com.property.maintenance.dto.PaymentProcessDto;
import com.property.maintenance.dto.StatusUpdateDto;
import org.junit.jupiter.api.MethodOrderer;
import org.junit.jupiter.api.Order;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.TestMethodOrder;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.http.MediaType;
import org.springframework.test.context.TestPropertySource;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.MvcResult;

import java.math.BigDecimal;
import java.time.LocalDateTime;

import static org.junit.jupiter.api.Assertions.*;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.*;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.*;

@SpringBootTest
@AutoConfigureMockMvc
@TestPropertySource(locations = "classpath:application-test.properties")
@TestMethodOrder(MethodOrderer.OrderAnnotation.class)
public class MaintenanceWorkflowIntegrationTest {

    @Autowired
    private MockMvc mockMvc;

    @Autowired
    private ObjectMapper objectMapper;

    private static Long createdRequestId;
    private static Long paymentId;

    @Test
    @Order(1)
    void step1_CreateMaintenanceRequest() throws Exception {
        MaintenanceRequestDto requestDto = new MaintenanceRequestDto();
        requestDto.setPropertyId(1L);
        requestDto.setTenantId(1L);
        requestDto.setCategory("PLUMBING");
        requestDto.setPriority("HIGH");
        requestDto.setDescription("Water heater is making loud noises and leaking water.");

        MvcResult result = mockMvc.perform(post("/maintenance-requests")
                .contentType(MediaType.APPLICATION_JSON)
                .content(objectMapper.writeValueAsString(requestDto)))
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.success").value(true))
                .andExpect(jsonPath("$.data.status").value("PENDING"))
                .andExpect(jsonPath("$.data.ticketNumber").exists())
                .andReturn();

        JsonNode root = objectMapper.readTree(result.getResponse().getContentAsString());
        createdRequestId = root.path("data").path("id").asLong();
        assertTrue(createdRequestId > 0);
    }

    @Test
    @Order(2)
    void step2_AssignTechnician() throws Exception {
        AssignTechnicianDto assignDto = new AssignTechnicianDto(
                1L,
                LocalDateTime.now().plusDays(1),
                "Assigned to Alex Rivera for water heater inspection."
        );

        mockMvc.perform(post("/maintenance-requests/" + createdRequestId + "/assign")
                .contentType(MediaType.APPLICATION_JSON)
                .content(objectMapper.writeValueAsString(assignDto)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.success").value(true))
                .andExpect(jsonPath("$.data.status").value("ASSIGNED"))
                .andExpect(jsonPath("$.data.technicianId").value(1));
    }

    @Test
    @Order(3)
    void step3_AcceptMaintenanceRequest() throws Exception {
        mockMvc.perform(post("/maintenance-requests/" + createdRequestId + "/accept"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.success").value(true))
                .andExpect(jsonPath("$.data.status").value("IN_PROGRESS"));
    }

    @Test
    @Order(4)
    void step4_CompleteMaintenanceRequestWithCosts() throws Exception {
        StatusUpdateDto updateDto = new StatusUpdateDto();
        updateDto.setStatus("COMPLETED");
        updateDto.setWorkPerformed("Replaced pressure relief valve and flushed sediment build-up from heating tank.");
        updateDto.setLaborCost(new BigDecimal("130.00"));
        updateDto.setPartsCost(new BigDecimal("45.00"));
        updateDto.setNotes("Heater tested and operating normally.");

        mockMvc.perform(patch("/maintenance-requests/" + createdRequestId + "/status")
                .contentType(MediaType.APPLICATION_JSON)
                .content(objectMapper.writeValueAsString(updateDto)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.success").value(true))
                .andExpect(jsonPath("$.data.status").value("COMPLETED"));
    }

    @Test
    @Order(5)
    void step5_VerifyAutoGeneratedInvoiceAndPayment() throws Exception {
        MvcResult result = mockMvc.perform(get("/maintenance-costs/request/" + createdRequestId))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.success").value(true))
                .andExpect(jsonPath("$.data.laborCost").value(130.00))
                .andExpect(jsonPath("$.data.partsCost").value(45.00))
                .andExpect(jsonPath("$.data.totalCost").value(175.00))
                .andExpect(jsonPath("$.data.paymentStatus").value("PENDING"))
                .andExpect(jsonPath("$.data.invoiceNumber").exists())
                .andReturn();

        JsonNode root = objectMapper.readTree(result.getResponse().getContentAsString());
        paymentId = root.path("data").path("id").asLong();
        assertTrue(paymentId > 0);
    }

    @Test
    @Order(6)
    void step6_ProcessPayment() throws Exception {
        PaymentProcessDto payDto = new PaymentProcessDto();
        payDto.setAmount(new BigDecimal("175.00"));
        payDto.setPaymentMethod("CREDIT_CARD");
        payDto.setTransactionReference("TXN-PAY-987654");

        mockMvc.perform(post("/maintenance-costs/" + paymentId + "/pay")
                .contentType(MediaType.APPLICATION_JSON)
                .content(objectMapper.writeValueAsString(payDto)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.success").value(true))
                .andExpect(jsonPath("$.data.paymentStatus").value("PAID"))
                .andExpect(jsonPath("$.data.amountPaid").value(175.00));
    }

    @Test
    @Order(7)
    void step7_VerifyHistoricalMaintenanceAuditRecord() throws Exception {
        mockMvc.perform(get("/maintenance-history/request/" + createdRequestId))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.success").value(true))
                .andExpect(jsonPath("$.data.totalCost").value(175.00))
                .andExpect(jsonPath("$.data.workPerformed").exists())
                .andExpect(jsonPath("$.data.status").value("COMPLETED"));
    }

    @Test
    @Order(8)
    void step8_CancelRequestFlow() throws Exception {
        // Create another request to test cancellation
        MaintenanceRequestDto requestDto = new MaintenanceRequestDto();
        requestDto.setPropertyId(2L);
        requestDto.setTenantId(2L);
        requestDto.setCategory("GENERAL");
        requestDto.setPriority("LOW");
        requestDto.setDescription("Window blind string broke.");

        MvcResult result = mockMvc.perform(post("/maintenance-requests")
                .contentType(MediaType.APPLICATION_JSON)
                .content(objectMapper.writeValueAsString(requestDto)))
                .andExpect(status().isCreated())
                .andReturn();

        JsonNode root = objectMapper.readTree(result.getResponse().getContentAsString());
        long cancelTargetId = root.path("data").path("id").asLong();

        mockMvc.perform(post("/maintenance-requests/" + cancelTargetId + "/cancel")
                .param("reason", "Tenant fixed the string themselves"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.success").value(true))
                .andExpect(jsonPath("$.data.status").value("CANCELLED"))
                .andExpect(jsonPath("$.data.cancellationReason").value("Tenant fixed the string themselves"));
    }
}
